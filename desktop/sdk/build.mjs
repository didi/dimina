import { cpSync, mkdirSync, existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { resolve, dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { spawnSync } from 'node:child_process'

const sdk = dirname(fileURLToPath(import.meta.url))
const root = resolve(sdk, '../..')
const platformArg = process.argv.slice(2).find(value => value.startsWith('--platform='))
const platform = platformArg?.slice(11) || `${process.platform === 'win32' ? 'windows' : process.platform}/${process.arch === 'x64' ? 'amd64' : process.arch}`
const out = join(sdk, 'dist')
function run(command, args, cwd = root, env = process.env) {
  const result = spawnSync(command, args, { cwd, env, stdio: 'inherit', shell: process.platform === 'win32' && command === 'pnpm' })
  if (result.error) throw result.error
  if (result.status !== 0) process.exit(result.status || 1)
}
mkdirSync(join(out, 'runtime'), { recursive: true })
run(process.execPath, [join(root, 'desktop/scripts/build.mjs'), `--platform=${platform}`, `--out=${join(out, 'runtime')}`], root, { ...process.env, DIMINA_DESKTOP_SDK: '1' })
mkdirSync(join(out, 'node'), { recursive: true })
run('pnpm', ['pack', '--out', join(out, 'node/dimina-desktop-sdk.tgz')], join(sdk, 'node'))
for (const language of ['qt', 'dotnet', 'tauri']) {
  cpSync(join(sdk, language), join(out, language), {
    recursive: true,
    filter: source => !['bin', 'obj', 'build', 'target', 'Cargo.lock', 'autogenerated', 'schemas'].includes(source.split(/[\\/]/).at(-1)),
  })
}
writeFileSync(join(out, 'README.md'), readFileSync(join(sdk, 'README.md'), 'utf8')
  .replaceAll('](../README.md', '](https://github.com/didi/dimina/blob/main/desktop/README.md'))
for (const name of ['LICENSE', 'LICENSE.md']) if (existsSync(join(root, name))) cpSync(join(root, name), join(out, name))
cpSync(join(root, 'fe/packages/container-sdk/THIRD-PARTY-NOTICES.md'), join(out, 'THIRD-PARTY-NOTICES.md'))
// Keep the licenses of the native runtime and its Go dependencies with the bundle.
const go = process.env.GO_BIN || (existsSync(join(root, '.build/toolchains/go/bin/go')) ? join(root, '.build/toolchains/go/bin/go') : 'go')
const modules = spawnSync(go, ['list', '-m', '-f', '{{.Path}}|{{.Version}}|{{.Dir}}', 'all'], {
  cwd: join(root, 'desktop'), env: { ...process.env, GOTOOLCHAIN: 'local' }, encoding: 'utf8',
})
if (modules.status !== 0) throw modules.error || new Error(modules.stderr)
for (const line of modules.stdout.trim().split('\n')) {
  const [name, version, directory] = line.split('|')
  if (!version || !directory) continue
  const destination = join(out, 'licenses', `${name.replaceAll('/', '_')}@${version}`)
  mkdirSync(destination, { recursive: true })
  for (const file of readdirSync(directory).filter(name => /^(LICENSE|COPYING|NOTICE)(\.|$)/i.test(name))) {
    cpSync(join(directory, file), join(destination, file), { recursive: true })
  }
}
const toolchain = spawnSync(go, ['env', 'GOROOT'], { encoding: 'utf8', env: { ...process.env, GOTOOLCHAIN: 'local' } })
if (toolchain.status !== 0) throw toolchain.error || new Error(toolchain.stderr)
cpSync(join(toolchain.stdout.trim(), 'LICENSE'), join(out, 'licenses', 'Go-LICENSE'))
console.log(`Desktop SDK: ${out}`)
