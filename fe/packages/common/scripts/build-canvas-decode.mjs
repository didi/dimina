import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { spawnSync } from 'node:child_process'

// Requires LLVM clang with the wasm32 backend and wasm-ld. Vite uses the
// committed bytecode; regeneration is needed only after changing the C source.
const args = process.argv.slice(2)
const option = (name, fallback) => {
	const index = args.indexOf(name)
	if (index < 0) return fallback
	if (!args[index + 1]) throw new Error(`Missing value for ${name}`)
	return args[index + 1]
}
const compiler = option('--cc', 'clang')
const linker = option('--ld', 'wasm-ld')
const source = fileURLToPath(new URL('../src/core/canvas-decode-kernel.c', import.meta.url))
const target = fileURLToPath(new URL('../src/core/canvas-decode-kernel-bytes.js', import.meta.url))
const temporary = mkdtempSync(join(tmpdir(), 'dimina-canvas-codec-'))
const run = (command, parameters) => {
	const result = spawnSync(command, parameters, { encoding: 'utf8' })
	if (result.error || result.status !== 0) throw new Error(`${command}: ${result.error?.message || result.stderr || result.stdout}`)
}
try {
	const object = join(temporary, 'codec.o')
	const binary = join(temporary, 'codec.wasm')
	run(compiler, ['--target=wasm32-unknown-unknown', '-std=c11', '-O3', '-msimd128', '-ffreestanding', '-fno-builtin',
		'-Wall', '-Wextra', '-Werror', '-c', source, '-o', object])
	run(linker, ['--no-entry', '--strip-all', '--export=text_ptr', '--export=input_ptr', '--export=output_ptr',
		'--export=decode_base64', '--export=decode', '--export=last_word', '--export=last_words',
		'--initial-memory=8388608', '--max-memory=8388608', object, '-o', binary])
	const bytes = readFileSync(binary)
	if (!WebAssembly.validate(bytes)) throw new Error('Generated Canvas codec is not valid Wasm')
	writeFileSync(target, '// Generated by scripts/build-canvas-decode.mjs from canvas-decode-kernel.c.\n'
		+ `export default new Uint8Array([${[...bytes].join(',')}])\n`)
	console.log(`Generated Canvas codec: ${bytes.length} bytes`)
}
finally { rmSync(temporary, { recursive: true, force: true }) }
